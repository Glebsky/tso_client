def clean_name(url):
    filename = url.split("/")[-1]
    name_without_ext = filename.rsplit(".", 1)[0]
    cleaned = re.sub(r'^icon[\s_]*', '', name_without_ext)
    cleaned = cleaned.lower()
    return cleaned

def main():
    base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    
    headers = {
        'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/114.0.0.0 Safari/537.36'
    }
    
    downloaded = 0
    skipped = 0
    
    print(f"Starting download of {len(URLS)} items...")
    
    for url in URLS:
        if not url.startswith("http"):
            continue
            
        cname = clean_name(url)
        
        # Route to the correct directory
        if "icons/resources" in url or "resources/" in url:
            target_dir = os.path.join(base_dir, "admin", "public", "images", "resources")
            target_path = os.path.join(target_dir, f"{cname}.png") # Local resources are .png
        else:
            target_dir = os.path.join(base_dir, "admin", "public", "images", "buildings")
            ext = "svg" if url.endswith(".svg") else "webp"
            target_path = os.path.join(target_dir, f"{cname}.{ext}")
            
        os.makedirs(target_dir, exist_ok=True)
        
        if os.path.exists(target_path):
            skipped += 1
            continue
            
        try:
            req = urllib.request.Request(url, headers=headers)
            with urllib.request.urlopen(req, timeout=8) as response:
                with open(target_path, 'wb') as out_file:
                    out_file.write(response.read())
            print(f"Downloaded: {cname} into {os.path.basename(target_dir)}")
            downloaded += 1
        except Exception as e:
            print(f"Failed to download {url}: {e}")
            
    print(f"\nDownload finished. Downloaded: {downloaded}, Skipped: {skipped}")

if __name__ == "__main__":
    main()
